const {test,expect}=require('@playwright/test');
test('header currency is inherited and read-only throughout entry, budgets, import and field settings',async({page,request})=>{
  let state=await (await request.get('/api/state')).json();
  await request.post('/api/test/reset',{headers:{'X-HomeAccounts-Token':state.csrf},data:{seed:true}});
  state=await (await request.get('/api/state')).json();
  page.on('pageerror',error=>{throw error;});
  await page.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():route.abort());
  await page.goto('/overview');await page.getByRole('combobox',{name:'Reporting currency'}).fill('USD');
  await page.getByRole('option',{name:/^USD/}).click();
  await page.getByRole('button',{name:'Add transaction',exact:true}).click();
  const dialog=page.locator('#entry-dialog');
  await expect(dialog.locator('[name=currency]')).toHaveValue('USD');
  await expect(dialog.locator('[name=currency]')).not.toBeEditable();
  await dialog.locator('[name=amount]').fill('12.50');
  await dialog.getByRole('button',{name:'Review transaction',exact:true}).click();
  await expect(page.locator('#review')).toContainText('USD');
  await page.getByText('Correct the proposed details',{exact:true}).click();
  await expect(page.locator('#correct-proposal [name=currency]')).toHaveValue('USD');
  await expect(page.locator('#correct-proposal [name=currency]')).not.toBeEditable();
  await page.keyboard.press('Escape');await page.keyboard.press('Escape');
  await page.goto('/entry');await expect(page.locator('#entry_currency')).toHaveValue('USD');await expect(page.locator('#entry_currency')).not.toBeEditable();
  await page.goto('/budgets');await page.locator('#new-budget').click();
  await expect(page.locator('#budget_currency')).toHaveValue('USD');await expect(page.locator('#budget_currency')).not.toBeEditable();await page.keyboard.press('Escape');
  await page.goto('/import');await page.getByRole('button',{name:'Try small fictional demo',exact:true}).click();
  await expect(page.locator('#import-mapping [name=currency]')).toHaveValue('USD');await expect(page.locator('#import-mapping [name=currency]')).not.toBeEditable();
  await page.goto('/setup');await page.getByRole('button',{name:'Edit current fields and shared categories',exact:true}).click();
  await expect(page.locator('[name=setup_currency]')).toHaveValue('USD');await expect(page.locator('[name=setup_currency]')).not.toBeEditable();
  const after=await (await request.get('/api/state')).json();
  expect(after.settings.currency).toBe('USD');expect(after.transactions).toEqual(state.transactions);expect(after.budgets).toEqual(state.budgets);expect(after.revision).toBe(state.revision);
});
